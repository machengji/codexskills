def set_run_font(run, name, size_pt, east=None):
    run.font.name = name
    run.font.size = Pt(size_pt)
    run.font.color.rgb = RGBColor(0, 0, 0)
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)
    rFonts.set(qn("w:eastAsia"), east or name)
    sz = OxmlElement("w:sz")
    sz.set(qn("w:val"), str(int(size_pt * 2)))
    rPr.append(sz)
    szCs = OxmlElement("w:szCs")
    szCs.set(qn("w:val"), str(int(size_pt * 2)))
    rPr.append(szCs)


def tight_p(p, before=0, after=0, line=240):
    pf = p.paragraph_format
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    pf.line_spacing = line / 240.0
    pPr = p._p.get_or_add_pPr()
    spacing = pPr.find(qn("w:spacing"))
    if spacing is None:
        spacing = OxmlElement("w:spacing")
        pPr.append(spacing)
    spacing.set(qn("w:before"), str(before))
    spacing.set(qn("w:after"), str(after))
    spacing.set(qn("w:line"), str(line))
    spacing.set(qn("w:lineRule"), "auto")


def text(doc, body, size=13, bold=False, line=480, font="微软雅黑", align=None):
    p = doc.add_paragraph()
    tight_p(p, 0, 0, line)
    if align:
        p.alignment = align
    run = p.add_run(body)
    set_run_font(run, font, size, "微软雅黑")
    run.bold = bold
    return p


def heading(doc, body, size=15):
    return text(doc, body, size, True, 500, "黑体")


def image(doc, img, caption):
    im = Image.open(img)
    w, h = im.size
    max_w = 6.1
    nw = max_w
    nh = max_w * h / w
    if nh > 4.6:
        nh = 4.6
        nw = nh * w / h
    p = doc.add_paragraph()
    tight_p(p, 0, 0, 240)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    run.add_picture(str(img), width=Inches(nw), height=Inches(nh))
    cap = doc.add_paragraph()
    tight_p(cap, 0, 0, 240)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = cap.add_run(caption)
    set_run_font(r, "微软雅黑", 10.5, "微软雅黑")
    r.italic = True


